-- =============================================================
-- 验证 1：每张表行数（完成标准：每张核心表 ≥ 5 行）
-- 预期：foods=8 / ratings=7 / favorites=6 / health_profiles=5
-- =============================================================
SELECT 'foods'           AS table_name, COUNT(*) AS row_count FROM foods
UNION ALL
SELECT 'ratings',          COUNT(*) FROM ratings
UNION ALL
SELECT 'favorites',        COUNT(*) FROM favorites
UNION ALL
SELECT 'health_profiles', COUNT(*) FROM health_profiles;

-- =============================================================
-- 验证 2：今天的学习目标——ratings 靠 "foodId" 关联 foods.id
-- JOIN 把两张表拼成一行：每条评分都能看到它评的是哪道菜
-- =============================================================
SELECT r."userId", r."foodId", f.name AS "foodName", r.score, r."updatedAt"
  FROM ratings r
  JOIN foods f ON f.id = r."foodId"
 ORDER BY r."userId", r."foodId";

-- =============================================================
-- 验证 3：favorites 同样靠 "foodId" 挂到 foods 上
-- =============================================================
SELECT fv."userId", fv."foodId", f.name AS "foodName"
  FROM favorites fv
  JOIN foods f ON f.id = fv."foodId"
 ORDER BY fv."userId", fv."foodId";

